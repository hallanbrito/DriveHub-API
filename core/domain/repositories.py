from typing import Optional, Protocol
from .entities import Brand, SaleProposal, Vehicle
class BrandRepository(Protocol):
    def get_or_create_by_name(self, name: str) -> Brand: ...
class VehicleRepository(Protocol):
    def get_by_id(self, vehicle_id: int) -> Optional[Vehicle]: ...
    def save(self, vehicle: Vehicle) -> Vehicle: ...
    def list_all(self) -> list[Vehicle]: ...
class SaleProposalRepository(Protocol):
    def get_by_id(self, proposal_id: int) -> Optional[SaleProposal]: ...
    def save(self, proposal: SaleProposal) -> SaleProposal: ...
    def list_all(self) -> list[SaleProposal]: ...
